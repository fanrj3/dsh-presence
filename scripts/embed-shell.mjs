// Embed scripts/presence-shell.ps1 into the cordis patch as the default shell
// for DSH's terminal panel.
//
//   node scripts/embed-shell.mjs        # rewrite cordis.patch.yml + presets/*.patch.yml
//   node scripts/embed-shell.mjs --check  # verify they are current (CI / pre-commit)
//
// The launcher is embedded as -EncodedCommand (UTF-16LE base64): no absolute
// path, no quoting layer between YAML, node-pty argv and PowerShell.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const sourcePath = join(here, 'presence-shell.ps1');
const BEGIN = '# >>> presence-shell (generated by scripts/embed-shell.mjs) >>>';
const END = '# <<< presence-shell <<<';

const source = readFileSync(sourcePath, 'utf8');
const encoded = Buffer.from(source, 'utf16le').toString('base64');

const block = `${BEGIN}
# The terminal panel's default shell: inside a remote workspace it opens an ssh
# session in the same folder; anywhere else it starts the local shell.
- id: terminal-controller
  config:
    shell:
      path: powershell.exe
      name: Presence
      args:
        - -NoLogo
        - -NoProfile
        - -ExecutionPolicy
        - Bypass
        - -EncodedCommand
        - ${encoded}
${END}`;

const targets = [
  join(root, 'cordis.patch.yml'),
  join(root, 'presets', 'fs.patch.yml'),
  join(root, 'presets', 'safe.patch.yml'),
];
const check = process.argv.includes('--check');
let stale = 0;

for (const target of targets) {
  const current = readFileSync(target, 'utf8');
  const start = current.indexOf(BEGIN);
  const end = current.indexOf(END);
  let next;
  if (start >= 0 && end > start) {
    next = `${current.slice(0, start)}${block}${current.slice(end + END.length)}`;
  } else {
    next = `${current.replace(/\s+$/u, '')}\n\n${block}\n`;
  }
  if (next === current) continue;
  if (check) {
    stale += 1;
    console.error(`stale: ${target}`);
  } else {
    writeFileSync(target, next);
    console.log(`updated: ${target}`);
  }
}

if (check && stale > 0) process.exit(1);
if (check) console.log('cordis patch launcher block is current');
console.log(`encoded ${source.length} chars -> ${encoded.length} base64 chars`);
